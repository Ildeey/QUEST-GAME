for (const customer of content.quest3.customers) {
  const categoryGoods = content.quest3.goods.filter(
    (good) => good.category === customer.id,
  )
  const scored = categoryGoods.map((good) => ({
    id: good.id,
    score: good.stats.reduce(
      (total, value, index) => total + value * customer.weights[index],
      0,
    ),
  }))
  const bestScore = Math.max(...scored.map((good) => good.score))
  const bestGoods = scored.filter((good) => good.score === bestScore)
  if (bestGoods.length !== 1 || bestGoods[0].id !== customer.match) {
    throw new Error(`Quest 3 must have one best match for ${customer.id}`)
  }
}
